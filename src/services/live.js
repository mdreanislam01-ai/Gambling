/**
 * Live-casino SIMULATION. Every table is a scripted studio round: the dealer,
 * the cards and the result are generated by this server and are always labelled
 * as simulated in the UI. Nothing here represents a real table or real money.
 */
const rankOf = (c) => c.slice(0, -1);

function spinFor(engine, seedKey, gameCfg = {}) {
  const rng = new Rng(seedKey);
  if (engine === 'roulette') {
    const index = rng.int(WHEEL_ORDER.length);
    return { type: 'roulette', index, number: WHEEL_ORDER[index], info: rouletteNumberInfo(WHEEL_ORDER[index]) };
  }
  if (engine === 'baccarat') {
    const deck = buildDeck(rng, 8);
    const cards = deck.slice(0, 6);
    const player = [cards[0], cards[2]];
    const banker = [cards[1], cards[3]];
    const tot = (cs) => cs.reduce((a, c) => { const r = rankOf(c); return a + (r === 'A' ? 1 : Number.isNaN(Number(r)) ? 0 : Number(r)); }, 0) % 10;
    return { type: 'baccarat', player, banker, playerTotal: tot(player), bankerTotal: tot(banker) };
  }
  if (engine === 'wheel') {
    return { type: 'wheel', segment: rng.int(WHEEL_SEGMENTS) };
  }
  return { type: 'generic', rng };
}

function evaluate(engine, spin, selection) {
  const bets = Array.isArray(selection?.bets) ? selection.bets : [];
  let payout = 0;
  let staked = 0;
  const legs = bets.map((b) => {
    const amount = Math.max(0, Math.round(Number(b.amount) || 0));
    staked += amount;
    if (engine === 'roulette') {
      const r = rouletteBetPayout(b.type, b.numbers, b.value, spin.number);
      const pay = r.won ? Math.floor(amount * r.mult) : 0;
      payout += pay;
      return { ...b, amount, won: r.won, payout: pay, mult: r.mult };
    }
    if (engine === 'baccarat') {
      const winner = spin.playerTotal > spin.bankerTotal ? 'player' : spin.bankerTotal > spin.playerTotal ? 'banker' : 'tie';
      const pays = { player: 2, banker: 1.95, tie: 9, pair_player: 11, pair_banker: 11 };
      const pp = rankOf(spin.player[0]) === rankOf(spin.player[1]);
      const bp = rankOf(spin.banker[0]) === rankOf(spin.banker[1]);
      let won = b.side === winner;
      if (b.side === 'pair_player') won = pp;
      if (b.side === 'pair_banker') won = bp;
      const pay = won ? Math.floor(amount * (pays[b.side] ?? 0)) : 0;
      payout += pay;
      return { ...b, amount, won, payout: pay };
    }
    if (engine === 'wheel') {
      const target = Number(b.target) || 2;
      const winning = Math.max(1, Math.min(WHEEL_SEGMENTS, Math.round((WHEEL_SEGMENTS * 0.96) / target)));
      const won = spin.segment < winning;
      const pay = won ? Math.floor(amount * (WHEEL_SEGMENTS / winning)) : 0;
      payout += pay;
      return { ...b, amount, won, payout: pay, winningSegments: winning };
    }
    return { ...b, amount, won: false, payout: 0 };
  });
  return { payout, staked, legs };
}

export class LiveEngine {
  constructor() {
    this.tables = new Map();
    this.timer = null;
    this.running = false;
  }

  start() {
    if (this.running) return;
    this.running = true;
    this.reload();
    this.timer = setInterval(() => this.tick(), 500);
    this.timer.unref?.();
  }
  stop() { this.running = false; clearInterval(this.timer); }

  reload() {
    const rows = listLiveTables();
    const seen = new Set();
    for (const t of rows) {
      seen.add(t.key);
      if (!this.tables.has(t.key)) {
        this.tables.set(t.key, {
          table: t,
          round: null,
          participants: new Map(),
          history: [],
          players: Math.max(3, Math.round(Math.random() * 28)),
        });
      } else {
        this.tables.get(t.key).table = t;
      }
    }
    for (const k of [...this.tables.keys()]) if (!seen.has(k)) this.tables.delete(k);
  }

  stateFor(key, userId = null) {
    const st = this.tables.get(key);
    if (!st) return null;
    const r = st.round;
    return {
      tableKey: key,
      status: r?.status ?? 'idle',
      roundId: r?.id ?? null,
      serverSeedHash: r?.hash ?? null,
      phaseEndsAt: r?.endsAt ?? null,
      spin: r?.status === 'payout' ? r.spin : null,
      revealedSeed: r?.status === 'payout' ? r.seed : null,
      history: st.history.slice(0, 20),
      dealer: st.table.dealer,
      players: st.players,
      minBet: st.table.minBet,
      maxBet: st.table.maxBet,
      myBets: [...st.participants.values()].filter((p) => p.userId === userId).map((p) => ({
        bet: p.betPublicId, round: p.roundId, stake: p.stake, selection: p.selection, status: p.status, payout: p.payout,
      })),
      participantCount: [...st.participants.values()].filter((p) => p.roundId === r?.id).length,
    };
  }

  tick() {
    if (!this.running || !liveEnabled()) return;
    const now = Date.now();
    for (const st of this.tables.values()) {
      try { this.step(st, now); } catch (err) {
        import('./audit.js').then((m) => m.logError({ code: 'live.tick', message: err.message, stack: err.stack, meta: { table: st.table.key } }));
      }
    }
  }

  step(st, now) {
    const t = st.table;
    if (!st.round) { this.openRound(st); return; }
    const r = st.round;
    if (r.status === 'betting' && now >= r.endsAt) {
      r.status = 'spinning';
      r.endsAt = now + 2200;
      this.broadcast(st);
      return;
    }
    if (r.status === 'spinning' && now >= r.endsAt) {
      this.resolve(st);
      r.status = 'payout';
      r.endsAt = now + Math.max(4000, Math.round(t.roundSeconds * 1000 * 0.25));
      this.broadcast(st);
      return;
    }
    if (r.status === 'payout' && now >= r.endsAt) {
      this.openRound(st);
    }
  }

  openRound(st) {
    const seed = crypto.randomBytes(12).toString('hex');
    const nonce = Number(get(`SELECT COALESCE(MAX(id),0) v FROM game_rounds WHERE game_key = :g`, { g: st.table.gameKey })?.v ?? 0) + 1;
    const r = run(
      `INSERT INTO game_rounds(game_key, status, server_seed, server_seed_hash, client_seed, nonce, visible_at)
       VALUES(:g,'betting',:s,:h,:c,:n,datetime('now'))`,
      { g: st.table.gameKey, s: seed, h: sha256(seed), c: st.table.key, n: nonce }
    );
    st.round = {
      id: Number(r.lastInsertRowid),
      status: 'betting',
      seed,
      hash: sha256(seed),
      nonce,
      endsAt: Date.now() + Math.max(6000, Math.round(st.table.roundSeconds * 1000 * 0.45)),
      spin: null,
      results: [],
    };
    broadcast('live:round', { tableKey: st.table.key, ...this.stateFor(st.table.key) });
  }

  resolve(st) {
    const r = st.round;
    const seedKey = `${r.seed}|${r.nonce}|${st.table.key}`;
    const spin = spinFor(st.table.engine, seedKey);
    r.spin = spin;
    const settled = [];
    tx(() => {
      for (const p of [...st.participants.values()]) {
        if (p.roundId !== r.id || p.status !== 'pending') continue;
        const { payout, legs, staked } = evaluate(st.table.engine, spin, p.selection);
        const status = payout === 0 ? 'lost' : 'won';
        settleBetTx({
          betId: p.betId, status, payout, multiplier: staked ? payout / staked : 0,
          outcome: { spin, legs, roundId: r.id, tableKey: st.table.key, simulated: true },
        });
        p.status = status;
        p.payout = payout;
        settled.push({ userId: p.userId, payout, status });
      }
    });
    run(
      `UPDATE game_rounds SET status = 'ended', result = :res, ended_at = datetime('now') WHERE id = :id`,
      { res: JSON.stringify({ spin, revealed: r.seed, players: settled.length }), id: r.id }
    );
    st.history.unshift({ id: r.id, at: new Date().toISOString(), spin: summarise(spin), seed: r.seed, hash: r.hash });
    st.history.length = Math.min(st.history.length, 40);
    st.players = Math.max(2, st.players + Math.round((Math.random() - 0.45) * 4));
    for (const [key, p] of [...st.participants]) if (p.roundId === r.id) { /* keep for display */ }
    broadcast(`live:result:${st.table.key}`, { tableKey: st.table.key, spin, settled: settled.length });
    for (const s of settled) {
      if (s.payout > 0) broadcast('live:win', { userId: s.userId, payout: s.payout, tableKey: st.table.key });
    }
  }

  broadcast(st) {
    broadcast(`live:phase:${st.table.key}`, { tableKey: st.table.key, ...this.stateFor(st.table.key) });
  }

  join({ user, tableKey, stake, selection }) {
    const st = this.tables.get(tableKey);
    if (!st || !st.round) throw new HttpError(503, 'live.table_closed');
    if (st.round.status !== 'betting') throw new HttpError(409, 'live.round_closed');
    const table = getLiveTable(tableKey);
    if (!table) throw new HttpError(404, 'live.table_not_found');
    if (stake < table.min_bet || stake > table.max_bet) throw new HttpError(400, 'err.stake_out_of_range', { min: table.min_bet, max: table.max_bet });
    return tx(() => {
      debit({ userId: user.id, amount: stake, noteKey: 'wallet.note.stake' });
      const row = openBetRow({
        userId: user.id, kind: 'live', gameKey: table.game_key, stake,
        selection, fair: { serverSeedHash: st.round.hash, nonce: st.round.nonce, clientSeed: tableKey, seedId: null },
        view: { tableKey, roundId: st.round.id, phase: 'betting' },
      });
      recordDay({ wagered: stake, paid: 0, count: 0 });
      run(`UPDATE bets SET round_id = :r WHERE id = :b`, { r: st.round.id, b: row.id });
      st.participants.set(row.public_id, {
        userId: user.id, betId: row.id, betPublicId: row.public_id, stake, selection,
        roundId: st.round.id, status: 'pending', payout: 0,
      });
      broadcast(`live:phase:${tableKey}`, { tableKey, ...this.stateFor(tableKey) });
      return { bet: { id: row.public_id, stake: row.stake, status: row.status, gameKey: row.game_key }, roundId: st.round.id, endsAt: st.round.endsAt };
    });
  }
}

const summarise = (spin) => {
  if (!spin) return null;
  if (spin.type === 'roulette') return { type: spin.type, number: spin.number, info: spin.info ?? rouletteNumberInfo(spin.number) };
  if (spin.type === 'baccarat') return { type: spin.type, playerTotal: spin.playerTotal, bankerTotal: spin.bankerTotal, player: spin.player, banker: spin.banker };
  if (spin.type === 'wheel') return { type: spin.type, segment: spin.segment };
  return { type: spin.type };
};

export const liveEngine = new LiveEngine();
